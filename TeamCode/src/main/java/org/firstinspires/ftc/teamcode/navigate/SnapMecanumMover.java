package org.firstinspires.ftc.teamcode.navigate;

import com.qualcomm.robotcore.hardware.DcMotor;
import com.qualcomm.robotcore.hardware.Gamepad;
import com.qualcomm.robotcore.hardware.IMU;
import com.qualcomm.robotcore.util.Range;

import org.firstinspires.ftc.robotcore.external.Telemetry;
import org.firstinspires.ftc.robotcore.external.navigation.AngleUnit;

/**
 * Think of this class as the robot's "driving brain" for a mecanum drivetrain.
 *
 * What it can do:
 * 1) Normal driver control (joysticks -> wheel power)
 * 2) Quick snap turns to fixed directions using triggers
 * 3) Auto-drive to a target position using odometry
 *
 * Where inputs come from:
 * - Gamepad sticks/triggers/buttons (driver commands)
 * - IMU heading (which way the robot is facing)
 * - Wheel encoder odometry (where the robot is on the field)
 *
 * What comes out:
 * - Power values sent to the four drive motors.
 *
 * =========================
 * STUDENT QUICKSTART
 * =========================
 *
 * Units Cheat Sheet
 * - Radians and degrees are both ways to measure angle.
 * - 180 degrees = PI radians.
 * - 90 degrees = PI/2 radians.
 * - -90 degrees = -PI/2 radians.
 * - Use Math.toRadians(deg) to convert degrees -> radians.
 * - Use Math.toDegrees(rad) to convert radians -> degrees.
 * - Distance: 1 foot = 12 inches.
 * - This file mostly computes in inches + radians internally for math consistency.
 *
 * Sign Convention Cheat Sheet
 * - forward command: + moves forward, - moves backward (robot frame).
 * - right command: + strafes right, - strafes left (robot frame).
 * - rotate command: signed turn command; direction follows this project's chosen sign convention.
 * - heading error = target heading - current heading.
 * - field-relative mode means joystick is interpreted in field directions, not robot directions.
 * - robot-relative mode means joystick is interpreted from robot's current point of view.
 *
 * 10-Step Flow (what happens each loop in driver control)
 * 1) `loop(...)` is called by FTC runtime.
 * 2) If `snap_to_tag` is true, this method exits so another controller owns movement.
 * 3) If A is pressed, IMU yaw is reset (current facing becomes near 0).
 * 4) Trigger edges are checked to decide whether to start snap-turn.
 * 5) Trigger memory flags are updated for next loop edge detection.
 * 6) Manual right-stick rotate is read.
 * 7) If manual rotate is strong enough, snap-turn is canceled.
 * 8) Else if snap-turn is active, rotate command is auto-generated by controller math.
 * 9) D-pad up/down and left bumper update the active drive speed scale.
 * 10) Drive mode is selected: right bumper = robot-relative, else field-relative.
 * 11) Final drive command is mixed into wheel powers and sent to motors.
 *
 * Layered Snap-Turn Control Notes
 * - Layer 1 (basic):
 *   The robot compares where it is facing vs where it should face, then turns to fix that gap.
 * - Layer 2 (deeper):
 *   Snap turn uses a PD-style controller.
 *   P part = main baseline turn push from heading error.
 *   D part = damping from error change rate to reduce overshoot.
 *   Extra shaping then handles acceleration/deceleration safely.
 *
 * Mini Tuning Table (what happens if you increase each value)
 * - SNAP_TURN_KP: stronger baseline turn push; faster response, but can overshoot more.
 * - SNAP_TURN_KD: stronger damping; less overshoot/jitter, but may feel slower or "heavy".
 * - SNAP_TURN_MAX_POWER: higher allowed turn power when far from target; faster big turns.
 * - SNAP_TURN_SETTLE_MAX_POWER: faster/slower final alignment in settle mode near target.
 * - BRAKE_ZONE_RADIANS: starts decelerating earlier (larger) or later (smaller).
 * - FINE_CONTROL_ZONE_RADIANS: enters gentle settle mode sooner (larger) or later (smaller).
 * - SNAP_TURN_MIN_POWER / SNAP_TURN_BRAKE_MIN_POWER: helps overcome static friction at low command.
 * - SNAP_TURN_MAX_COMMAND_SLEW_PER_SECOND: smoothness of acceleration/deceleration; lower = smoother, higher = snappier.
 * - TURN_STOP_DEADBAND_RADIANS: final stop tolerance; larger stops earlier, smaller aims more precisely.
 */
public class SnapMecanumMover {
    // Predefined snap headings for the trigger shortcuts.
    // In this codebase, 0 radians means field north.
    private static final double RIGHT_TRIGGER_TARGET_RADIANS = DriveConfig.RIGHT_TRIGGER_TARGET_RADIANS;
    private static final double LEFT_TRIGGER_TARGET_RADIANS = DriveConfig.LEFT_TRIGGER_TARGET_RADIANS;

    // Snap-turn controller tolerances and shaping constants.
    // Layer 1: these numbers control how "snappy" or "gentle" turning feels.
    // Layer 2: these values shape acceleration, deceleration, and settling behavior.
    private static final double TURN_STOP_DEADBAND_RADIANS = DriveConfig.TURN_STOP_DEADBAND_RADIANS;
    private static final double SETTLE_TOLERANCE_RADIANS = DriveConfig.SETTLE_TOLERANCE_RADIANS;
    private static final double BRAKE_ZONE_RADIANS = DriveConfig.BRAKE_ZONE_RADIANS;
    private static final double FINE_CONTROL_ZONE_RADIANS = DriveConfig.FINE_CONTROL_ZONE_RADIANS;
    // PD baseline gains (there is no I term in snap-turn path here).
    // Kp gives the baseline turn push from heading error.
    private static final double SNAP_TURN_KP = 0.76;
    // Kd adds damping using error-rate so the robot does not swing past target too hard.
    private static final double SNAP_TURN_KD = 0.60;
    // Turn acceleration/deceleration shaping limits.
    private static final double SNAP_TURN_MAX_POWER = DriveConfig.SNAP_TURN_MAX_POWER;
    private static final double SNAP_TURN_BRAKE_MAX_POWER = DriveConfig.SNAP_TURN_BRAKE_MAX_POWER;
    private static final double SNAP_TURN_SETTLE_MAX_POWER = DriveConfig.SNAP_TURN_SETTLE_MAX_POWER;
    private static final double SNAP_TURN_MIN_POWER = DriveConfig.SNAP_TURN_MIN_POWER;
    private static final double SNAP_TURN_BRAKE_MIN_POWER = DriveConfig.SNAP_TURN_BRAKE_MIN_POWER;
    private static final double MAX_SETTLED_TURN_RATE_RADIANS = DriveConfig.MAX_SETTLED_TURN_RATE_RADIANS;
    private static final int REQUIRED_SETTLED_LOOPS = DriveConfig.REQUIRED_SETTLED_LOOPS;
    private static final double TRIGGER_THRESHOLD = DriveConfig.TRIGGER_THRESHOLD;
    private static final double MANUAL_ROTATE_DEADBAND = DriveConfig.MANUAL_ROTATE_DEADBAND;
    private static final double SNAP_TURN_MAX_ERROR_RATE_RADIANS_PER_SECOND = DriveConfig.SNAP_TURN_MAX_ERROR_RATE_RADIANS_PER_SECOND;
    private static final double SNAP_TURN_ERROR_RATE_FILTER_ALPHA = DriveConfig.SNAP_TURN_ERROR_RATE_FILTER_ALPHA;
    // Slew limit: max amount rotate command is allowed to change per second.
    // This smooths acceleration so command does not jump suddenly.
    private static final double SNAP_TURN_MAX_COMMAND_SLEW_PER_SECOND = DriveConfig.SNAP_TURN_MAX_COMMAND_SLEW_PER_SECOND;
    private static final double DEFAULT_DRIVE_SPEED_SCALE = DriveConfig.DEFAULT_DRIVE_SPEED_SCALE;
    private static final double MIN_DRIVE_SPEED_SCALE = DriveConfig.MIN_DRIVE_SPEED_SCALE;
    private static final double MAX_DRIVE_SPEED_SCALE = DriveConfig.MAX_DRIVE_SPEED_SCALE;
    private static final double DRIVE_SPEED_SCALE_STEP = DriveConfig.DRIVE_SPEED_SCALE_STEP;

    private final DcMotor frontLeftDrive;
    private final DcMotor frontRightDrive;
    private final DcMotor backLeftDrive;
    private final DcMotor backRightDrive;
    private final IMU imu;

    // Runtime state for the trigger-based snap-turn controller.
    // Think of these as the controller's memory from one loop to the next.
    // Without this memory, derivative terms and settle logic would not work.
    private boolean snapTurnActive = false;
    private double targetHeadingRadians = 0.0;
    private boolean leftTriggerWasPressed = false;
    private boolean rightTriggerWasPressed = false;
    private double previousHeadingErrorRadians = 0.0;
    private long previousSnapUpdateTimeNanos = 0L;
    private double lastTurnRateRadiansPerSecond = 0.0;
    private double filteredHeadingErrorRateRadiansPerSecond = 0.0;
    private double previousRotateCommand = 0.0;
    private boolean snapTurnSettling = false;
    private int settledLoopCount = 0;
    private double driveSpeedScale = DEFAULT_DRIVE_SPEED_SCALE;
    private boolean dpadUpWasPressed = false;
    private boolean dpadDownWasPressed = false;
    private boolean leftBumperWasPressed = false;

    // Odometry is created only if a caller actually uses localization/navigation features.
    private MecanumWheelMotorOdometry odometry;

    // Target navigation orchestration is delegated to a dedicated helper.
    private final TargetNavigationController targetNavigationController = new TargetNavigationController();

    /**
     * Builds this drive helper and stores references to hardware.
     *
     * This constructor does not move the robot. It only saves hardware handles so
     * later methods can read sensors and command motors.
     *
     * Parameters passed in from your OpMode:
     * - frontLeftDrive/frontRightDrive/backLeftDrive/backRightDrive: motor objects from hardwareMap
     * - imu: IMU object from hardwareMap
     *
     * Outcome:
     * - This class can now read heading and command wheel powers.
     */
    public SnapMecanumMover(
            DcMotor frontLeftDrive,
            DcMotor frontRightDrive,
            DcMotor backLeftDrive,
            DcMotor backRightDrive,
            IMU imu
    ) {
        this.frontLeftDrive = frontLeftDrive;
        this.frontRightDrive = frontRightDrive;
        this.backLeftDrive = backLeftDrive;
        this.backRightDrive = backRightDrive;
        this.imu = imu;
    }

    /**
     * Main TeleOp update for driving. Call this once every loop.
     *
     * Parameters:
     * - gamepad1: main driver's controls
     * - gamepad2: second driver's controls (kept for compatible method signature)
     * - telemetry: debug output object for Driver Station
     * - snap_to_tag: true when another routine should own motion for this loop
     *
     * Control priority (important for long-term maintainability):
     * 1) If snap_to_tag is true, this method exits immediately.
     * 2) Manual rotate stick cancels snap-turn instantly.
     * 3) Trigger edge can start snap-turn.
     * 4) Drive mode switch chooses robot-relative or field-relative.
     *
     * Why this priority exists:
     * - Prevents two controllers from commanding motion at the same time.
     * - Gives drivers immediate override when they touch right stick X.
     */
    public void loop(Gamepad gamepad1, Gamepad gamepad2, Telemetry telemetry, boolean snap_to_tag) {
        /*
        telemetry.addLine("Press A to reset Yaw");
        telemetry.addLine("Hold right bumper to drive in robot relative");
        telemetry.addLine("The left joystick sets the robot direction");
        telemetry.addLine("Moving the right joystick left and right turns the robot");
        telemetry.addLine("Left trigger snaps to 90° clockwise from field north");
        telemetry.addLine("Right trigger snaps to 90° counterclockwise from field north");
        */

        // If another routine is temporarily taking over motion control (for example tag snapping),
        // skip the normal driver loop so commands do not fight each other.
        if (snap_to_tag) {
            return;
        }

        applyYawResetAndSnapCancelIfRequested(gamepad1);
        processSnapTurnTriggerEdges(gamepad1);
        updateDriveSpeedScale(gamepad1);
        double rotateCommand = resolveRotateCommand(gamepad1, telemetry);

        telemetry.addData("Drive speed scale", "%.2f", driveSpeedScale);
        //telemetry.addData("Heading (deg)", Math.toDegrees(getCurrentHeadingRadians()));
        //telemetry.addData("Snap turn", snapTurnActive ? "ACTIVE" : "OFF");
        /*
        if (snapTurnActive) {
            telemetry.addData("Target heading (deg)", Math.toDegrees(targetHeadingRadians));
            telemetry.addData("Heading error (deg)", Math.toDegrees(AngleUnit.normalizeRadians(targetHeadingRadians - getCurrentHeadingRadians())));
            telemetry.addData("Turn rate (deg/s)", Math.toDegrees(lastTurnRateRadiansPerSecond));
            telemetry.addData("Settling", snapTurnSettling ? "YES" : "NO");
        }
        */
        driveFromSelectedMode(gamepad1, rotateCommand);
    }

    private void applyYawResetAndSnapCancelIfRequested(Gamepad gamepad1) {
        // Resetting yaw redefines the robot's current facing direction as zero.
        if (gamepad1.a) {
            imu.resetYaw();
            snapTurnActive = false;
        }
    }

    private void processSnapTurnTriggerEdges(Gamepad gamepad1) {
        boolean leftTriggerPressed = gamepad1.left_trigger > TRIGGER_THRESHOLD;
        boolean rightTriggerPressed = gamepad1.right_trigger > TRIGGER_THRESHOLD;

        // Edge trigger logic:
        // We start snap-turn only when trigger transitions from not-pressed -> pressed.
        // This avoids re-initializing controller state every single loop while held.
        if (leftTriggerPressed && !rightTriggerWasPressed) {
            startSnapTurn(LEFT_TRIGGER_TARGET_RADIANS);
        } else if (rightTriggerPressed && !leftTriggerWasPressed) {
            startSnapTurn(RIGHT_TRIGGER_TARGET_RADIANS);
        }

        leftTriggerWasPressed = leftTriggerPressed;
        rightTriggerWasPressed = rightTriggerPressed;
    }

    private double resolveRotateCommand(Gamepad gamepad1, Telemetry telemetry) {
        // Snap reaction rule:
        // Manual turn input overrides snap-turn immediately.
        // This makes driver control feel predictable and safe.
        double rotateCommand = gamepad1.right_stick_x;
        if (Math.abs(rotateCommand) > MANUAL_ROTATE_DEADBAND) {
            snapTurnActive = false;
        } else if (snapTurnActive) {
            // Negated here to match the sign convention already used by the rest of the drive code.
            rotateCommand = -getSnapTurnCommand(telemetry);
        }

        return rotateCommand;
    }

    private void updateDriveSpeedScale(Gamepad gamepad1) {
        boolean dpadUpPressed = gamepad1.dpad_up;
        boolean dpadDownPressed = gamepad1.dpad_down;
        boolean leftBumperPressed = gamepad1.left_bumper;

        if (dpadUpPressed && !dpadUpWasPressed) {
            driveSpeedScale = Range.clip(
                    driveSpeedScale + DRIVE_SPEED_SCALE_STEP,
                    MIN_DRIVE_SPEED_SCALE,
                    MAX_DRIVE_SPEED_SCALE
            );
        }

        if (dpadDownPressed && !dpadDownWasPressed) {
            driveSpeedScale = Range.clip(
                    driveSpeedScale - DRIVE_SPEED_SCALE_STEP,
                    MIN_DRIVE_SPEED_SCALE,
                    MAX_DRIVE_SPEED_SCALE
            );
        }

        if (leftBumperPressed && !leftBumperWasPressed) {
            driveSpeedScale = DEFAULT_DRIVE_SPEED_SCALE;
        }

        dpadUpWasPressed = dpadUpPressed;
        dpadDownWasPressed = dpadDownPressed;
        leftBumperWasPressed = leftBumperPressed;
    }

    private void driveFromSelectedMode(Gamepad gamepad1, double rotateCommand) {
        if (gamepad1.right_bumper) {
            // Robot-relative mode: stick directions are interpreted from the robot's point of view.
            drive(-gamepad1.left_stick_y, gamepad1.left_stick_x, rotateCommand);
        } else {
            // Field-relative mode: stick directions are interpreted from the field's point of view.
            driveFieldRelative(-gamepad1.left_stick_y, gamepad1.left_stick_x, rotateCommand);
        }
    }

    /** Starts the same snap-turn target as pressing the right trigger shortcut. */
    public void snapTurnRightTriggerShortcut() {
        startSnapTurn(RIGHT_TRIGGER_TARGET_RADIANS);
    }

    /** Starts the same snap-turn target as pressing the left trigger shortcut. */
    public void snapTurnLeftTriggerShortcut() {
        startSnapTurn(LEFT_TRIGGER_TARGET_RADIANS);
    }

    /** Returns true when trigger-style snap-turn is currently active. */
    public boolean isSnapTurnActive() {
        return snapTurnActive;
    }

    /**
     * Runs one control step for trigger-style snap-turn without joystick translation.
     *
     * @return true when snap-turn is complete (inactive), false while still turning.
     */
    public boolean stepSnapTurn(Telemetry telemetry) {
        if (!snapTurnActive) {
            return true;
        }

        double rotateCommand = -getSnapTurnCommand(telemetry);
        drive(0.0, 0.0, rotateCommand);
        return !snapTurnActive;
    }

    /**
     * Starts a snap-turn request toward a target heading.
     *
     * Parameter:
     * - headingRadians: direction to face, in radians
     *
     * Outcome:
     * - Controller state is reset so old error history does not pollute new turn.
     * - snapTurnActive is enabled.
     */
    private void startSnapTurn(double headingRadians) {
        targetHeadingRadians = AngleUnit.normalizeRadians(headingRadians); // Keep heading wrapped to [-pi, +pi].
        previousHeadingErrorRadians = AngleUnit.normalizeRadians(targetHeadingRadians - getCurrentHeadingRadians());
        previousSnapUpdateTimeNanos = System.nanoTime(); // Timestamp for derivative dt.
        lastTurnRateRadiansPerSecond = 0.0;
        filteredHeadingErrorRateRadiansPerSecond = 0.0;
        previousRotateCommand = 0.0;
        snapTurnSettling = false;
        settledLoopCount = 0;
        snapTurnActive = true;
    }

    /**
     * Calculates rotation command for snap-turn control.
     *
     * Parameter:
     * - telemetry: available for debug info (most telemetry lines are currently commented)
     *
     * Returns:
     * - rotation command to send into drive methods (roughly -1.0 .. +1.0)
     *
     * Internals in plain language:
     * 1) Measure heading error (target - current)
     * 2) Measure how quickly error is changing (derivative)
     * 3) Filter noisy derivative values
     * 4) Use PD baseline math to create rotate command
     * 5) Apply acceleration/deceleration shaping (zones + min/max limits + slew limit)
     * 6) Settle/stop once close and stable
     *
     * Layered explanation:
     * - Layer 1 (basic): turn fast when far, slow down when close.
     * - Layer 2 (deeper):
     *   * Kp sets baseline turn push from angle error.
     *   * Kd damps quick error changes.
     *   * Brake zone + settle zone decelerate near target.
     *   * Slew limiter smooths acceleration/deceleration between loops.
     */
    private double getSnapTurnCommand(Telemetry telemetry) {
        // Positive/negative sign here tells which direction robot still needs to rotate.
        double headingError = AngleUnit.normalizeRadians(targetHeadingRadians - getCurrentHeadingRadians());
        /*
        telemetry.addData("heading error value", Math.abs(headingError));
        telemetry.addData("deadband", TURN_STOP_DEADBAND_RADIANS);
        telemetry.addData("settled loop count", settledLoopCount);
        */
        long nowNanos = System.nanoTime();
        double deltaTimeSeconds = (nowNanos - previousSnapUpdateTimeNanos) / 1_000_000_000.0; // Convert ns to seconds.

        if (deltaTimeSeconds <= 0.0) {
            // Safety fallback if timer resolution/glitch gives zero or negative dt.
            // Prevents divide-by-zero in derivative math.
            deltaTimeSeconds = 0.001;
        }

        double errorDeltaRadians = AngleUnit.normalizeRadians(headingError - previousHeadingErrorRadians);
        double rawErrorRateRadiansPerSecond = errorDeltaRadians / deltaTimeSeconds;
        // Limit impossible derivative spikes from IMU sample jitter or angle wrap transitions.
        rawErrorRateRadiansPerSecond = Range.clip(
                rawErrorRateRadiansPerSecond,
                -SNAP_TURN_MAX_ERROR_RATE_RADIANS_PER_SECOND,
                SNAP_TURN_MAX_ERROR_RATE_RADIANS_PER_SECOND
        );

        // Low-pass filter derivative so tiny heading jitter does not create direction-flip jerk.
        filteredHeadingErrorRateRadiansPerSecond =
                (SNAP_TURN_ERROR_RATE_FILTER_ALPHA * filteredHeadingErrorRateRadiansPerSecond)
                        + ((1.0 - SNAP_TURN_ERROR_RATE_FILTER_ALPHA) * rawErrorRateRadiansPerSecond);
        lastTurnRateRadiansPerSecond = -filteredHeadingErrorRateRadiansPerSecond;

        // Once the heading is close enough, stop the snap-turn controller entirely.
        if (Math.abs(headingError) <= TURN_STOP_DEADBAND_RADIANS) {
            return stopSnapTurnAndReturnZero(headingError, nowNanos);
        }

        boolean overshotTarget = Math.signum(previousHeadingErrorRadians) != Math.signum(headingError)
                && Math.abs(previousHeadingErrorRadians) > TURN_STOP_DEADBAND_RADIANS;
        // Sign flip means error crossed through zero, so robot passed target heading.

        // Snap reaction near target:
        // If we crossed the target or entered fine zone, switch to settle mode (gentler turning).
        if (overshotTarget || Math.abs(headingError) <= FINE_CONTROL_ZONE_RADIANS) {
            snapTurnSettling = true;
        }

        boolean headingWithinTolerance = Math.abs(headingError) <= SETTLE_TOLERANCE_RADIANS;
        boolean turnRateIsLow = Math.abs(lastTurnRateRadiansPerSecond) <= MAX_SETTLED_TURN_RATE_RADIANS;

        if (headingWithinTolerance && turnRateIsLow) {
            settledLoopCount++;
        } else {
            settledLoopCount = 0;
        }

        // Require several consecutive settled loops before considering the robot stable.
        if (settledLoopCount >= REQUIRED_SETTLED_LOOPS
                && Math.abs(headingError) <= TURN_STOP_DEADBAND_RADIANS) {
            return stopSnapTurnAndReturnZero(headingError, nowNanos);
        }

        // PD baseline command before shaping.
        double rotateCommand =
                (headingError * SNAP_TURN_KP)
                        + (filteredHeadingErrorRateRadiansPerSecond * SNAP_TURN_KD);

        double absoluteError = Math.abs(headingError);
        double maxAllowedPower;
        double minAllowedPower = 0.0;

        // Deceleration shaping:
        // - Large error: allow stronger turning.
        // - Brake zone: taper power down as we approach target.
        // - Settle mode: very small cap for precise final alignment.
        if (snapTurnSettling) {
            maxAllowedPower = SNAP_TURN_SETTLE_MAX_POWER;
        } else if (absoluteError <= BRAKE_ZONE_RADIANS) {
            double brakeBlend = Range.clip(absoluteError / BRAKE_ZONE_RADIANS, 0.0, 1.0);
            maxAllowedPower = SNAP_TURN_BRAKE_MAX_POWER
                    + (SNAP_TURN_MAX_POWER - SNAP_TURN_BRAKE_MAX_POWER) * brakeBlend;
            minAllowedPower = SNAP_TURN_BRAKE_MIN_POWER * brakeBlend;
        } else {
            maxAllowedPower = SNAP_TURN_MAX_POWER;
            minAllowedPower = SNAP_TURN_MIN_POWER;
        }

        rotateCommand = Range.clip(rotateCommand, -maxAllowedPower, maxAllowedPower); // Keep command in safe bounds.

        if (minAllowedPower > 0.0 && Math.abs(rotateCommand) < minAllowedPower) {
            rotateCommand = Math.copySign(minAllowedPower, rotateCommand);
            // Keep same direction, but ensure enough power to overcome static friction.
        }

        // Acceleration/deceleration smoothing:
        // slew limiting prevents instant command jumps (reduces jerk).
        double maxDeltaCommand = SNAP_TURN_MAX_COMMAND_SLEW_PER_SECOND * deltaTimeSeconds;
        rotateCommand = Range.clip(
                rotateCommand,
                previousRotateCommand - maxDeltaCommand,
                previousRotateCommand + maxDeltaCommand
        );
        previousRotateCommand = rotateCommand;

        // Save state for next loop's derivative calculation.
        previousHeadingErrorRadians = headingError;
        previousSnapUpdateTimeNanos = nowNanos;

        return rotateCommand;
    }

    private double stopSnapTurnAndReturnZero(double headingError, long nowNanos) {
        snapTurnActive = false;
        snapTurnSettling = false;
        settledLoopCount = 0;
        previousHeadingErrorRadians = headingError;
        previousSnapUpdateTimeNanos = nowNanos;
        lastTurnRateRadiansPerSecond = 0.0;
        filteredHeadingErrorRateRadiansPerSecond = 0.0;
        previousRotateCommand = 0.0;
        return 0.0;
    }

    /**
     * Reads current heading from the IMU.
     *
     * Returns:
     * - yaw in radians. After imu.resetYaw(), current direction becomes approximately 0.
     */
    private double getCurrentHeadingRadians() {
        return imu.getRobotYawPitchRollAngles().getYaw(AngleUnit.RADIANS);
    }

    /**
     * Drive in field coordinates.
     *
     * Parameters:
     * - forward: desired movement along field forward/back axis
     * - right: desired movement along field left/right axis
     * - rotate: desired spin command
     *
     * Why this method exists:
     * - Driver can push stick "up" and robot goes "up-field" even if robot is rotated.
     *
     * Operation:
     * - Convert Cartesian input (forward/right) into polar (angle + magnitude)
     * - Subtract robot heading to convert into robot-local direction
     * - Convert back to forward/right in robot frame
     * - Delegate to drive(...)
     */
    public void driveFieldRelative(double forward, double right, double rotate) {
        double theta = Math.atan2(forward, right); // Field-frame movement angle.
        double r = Math.hypot(right, forward); // Movement magnitude (0..about 1 for joystick usage).

        theta = AngleUnit.normalizeRadians(theta - getCurrentHeadingRadians()); // Re-express vector in robot frame.

        double newForward = r * Math.sin(theta);
        double newRight = r * Math.cos(theta);

        drive(newForward, newRight, rotate);
    }

    /**
     * Drive in robot-local coordinates.
     *
     * Parameters:
     * - forward: +forward, -backward
     * - right: +right strafe, -left strafe
     * - rotate: signed turn request
     *
     * Output:
     * - Computes and sends four motor powers for a mecanum chassis.
     *
     * Maintenance tip:
     * - If wheel directions or wiring changes, verify sign pattern here plus motor direction setup.
     */
    public void drive(double forward, double right, double rotate) {
        double frontLeftPower = forward + right + rotate;
        double frontRightPower = forward - right - rotate;
        double backRightPower = forward + right - rotate;
        double backLeftPower = forward - right + rotate;
        // This + / - matrix is the standard mecanum mix for translation + rotation.

        // Normalize by largest magnitude so no motor exceeds |1.0|,
        // while preserving the ratio between wheel powers.
        double maxPower = 1.0;
        double maxSpeed = driveSpeedScale;

        maxPower = Math.max(maxPower, Math.abs(frontLeftPower));
        maxPower = Math.max(maxPower, Math.abs(frontRightPower));
        maxPower = Math.max(maxPower, Math.abs(backRightPower));
        maxPower = Math.max(maxPower, Math.abs(backLeftPower));

        frontLeftDrive.setPower(maxSpeed * (frontLeftPower / maxPower));
        frontRightDrive.setPower(maxSpeed * (frontRightPower / maxPower));
        backLeftDrive.setPower(maxSpeed * (backLeftPower / maxPower));
        backRightDrive.setPower(maxSpeed * (backRightPower / maxPower));
    }

    /**
     * Returns odometry helper, creating it on first use.
     *
     * Why delayed creation helps:
     * - TeleOp-only callers do not pay setup cost for odometry if never used.
     */
    public MecanumWheelMotorOdometry getOdometry() {
        if (odometry == null) {
            odometry = new MecanumWheelMotorOdometry(
                    frontLeftDrive,
                    frontRightDrive,
                    backLeftDrive,
                    backRightDrive,
                    imu
            );
        }

        return odometry;
    }

    /**
     * Initializes odometry internals (encoder baselines, state memory).
     * Call this before trusting odometry-based position/heading values.
     */
    public void initializeOdometry() {
        getOdometry().initialize();
    }

    /**
     * Stores a new navigation target pose (X, Y, heading).
     *
     * Parameters:
     * - xInches/yInches: destination in field inches
     * - headingRadians: final orientation goal in radians
     *
     * Important behavior:
     * - Optionally clamps target inside known field bounds.
     * - Resets derivative memory so heading controller starts clean on new target.
     */
    public void setTargetPose(double xInches, double yInches, double headingRadians) {
        targetNavigationController.setTargetPose(xInches, yInches, headingRadians, getOdometry());
    }

    /**
     * Runs one update step of autonomous navigation toward current target.
     *
     * Returns:
     * - true  -> target reached (or no target exists)
     * - false -> still traveling
     *
     * High-level flow:
     * 1) Update odometry
     * 2) Stop immediately if target missing
     * 3) Compute distance/heading errors
     * 4) Build translation command from XY error
     * 5) Build rotation command from heading error
     * 6) Apply safety limits + near-target slowdowns
     * 7) Drive field-relative and store command for telemetry
     */
    public boolean navigateToTarget() {
        boolean targetReached = targetNavigationController.navigateToTarget(getOdometry(), this::driveFieldRelative);

        // Target navigation and trigger-based snap-turn are both heading controllers, so disable the
        // trigger-based one while autonomous target motion is active.
        if (!targetReached) {
            snapTurnActive = false;
        }

        return targetReached;
    }

    /**
     * Checks whether robot is within both allowed position error and heading error.
     *
     * Returns:
     * - true when "close enough" by configured tolerances.
     */
    public boolean isAtTarget() {
        return targetNavigationController.isAtTarget(getOdometry());
    }

    /**
     * Cancels current target and clears navigation state.
     *
     * Outcome:
     * - Target is removed
     * - Error memory cleared
     * - Robot commanded to stop via stopTargetNavigation()
     */
    public void cancelTarget() {
        targetNavigationController.cancelTarget(this::driveFieldRelative);
    }

    /**
     * Adds human-readable telemetry for target navigation status.
     *
     * Useful for students:
     * - Shows if navigation is active
     * - Shows current distance and heading error
     * - Shows last command actually issued by controller
     */
    public void addTargetNavigationTelemetry(Telemetry telemetry) {
        targetNavigationController.addTargetNavigationTelemetry(telemetry, getOdometry());
    }

    /**
     * Small immutable data object for one movement command.
     *
     * Fields:
     * - forward: forward/back command component
     * - right: strafe command component
     * - rotate: turn command component
     */
    public static class NavigationCommand {
        public final double forward;
        public final double right;
        public final double rotate;

        /**
         * Creates a command package.
         *
         * Parameters:
         * - forward/right/rotate values exactly as sent to driveFieldRelative(...)
         */
        public NavigationCommand(double forward, double right, double rotate) {
            this.forward = forward;
            this.right = right;
            this.rotate = rotate;
        }
    }
}

